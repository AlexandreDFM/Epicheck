/**
 * File Name: app.config.ts
 * Description: Dynamic Expo config. The static part stays in app.json;
 *              this file only adds the version numbers, derived from the
 *              "version" field of package.json (single source of truth).
 *
 * 1.2.1 -> expo.version "1.2.1", android.versionCode 10201,
 *          ios.buildNumber "10201" (MAJOR * 10000 + MINOR * 100 + PATCH).
 * Bump with `pnpm run version:bump patch|minor|major`.
 */

import type { ConfigContext, ExpoConfig } from "expo/config";
import {
    withAppBuildGradle,
    withProjectBuildGradle,
    withXcodeProject,
    type ConfigPlugin,
} from "expo/config-plugins";

import { version } from "./package.json";

/** Build number shared by Android (versionCode) and iOS (CFBundleVersion) */
export function buildNumberOf(semver: string): number {
    const match = /^(\d+)\.(\d+)\.(\d+)$/.exec(semver);
    if (!match) {
        throw new Error(`package.json version "${semver}" is not X.Y.Z`);
    }
    const [major, minor, patch] = match.slice(1).map(Number);
    if (minor > 99 || patch > 99) {
        throw new Error(`minor and patch must stay below 100 (${semver})`);
    }
    return major * 10000 + minor * 100 + patch;
}

/**
 * expo prebuild writes the version to Info.plist but can leave the Xcode
 * build settings at 1.0 / 1; set them too so that Xcode builds match.
 */
const withXcodeVersion: ConfigPlugin<{ version: string; build: string }> = (
    config,
    { version: marketingVersion, build },
) =>
    withXcodeProject(config, (mod) => {
        const configurations = mod.modResults.pbxXCBuildConfigurationSection();
        for (const entry of Object.values(configurations)) {
            const settings = (
                entry as { buildSettings?: Record<string, string> }
            ).buildSettings;
            if (settings?.PRODUCT_BUNDLE_IDENTIFIER) {
                settings.MARKETING_VERSION = marketingVersion;
                settings.CURRENT_PROJECT_VERSION = build;
            }
        }
        return mod;
    });

const SIGNING_MARKER = "EpiCheck release key";

/**
 * Sign Android release builds with the key given by the environment:
 * ANDROID_KEYSTORE_FILE, ANDROID_KEYSTORE_PASSWORD, ANDROID_KEY_ALIAS,
 * ANDROID_KEY_PASSWORD (GitHub secrets in .github/workflows/android.yaml,
 * or exported locally). Without ANDROID_KEYSTORE_FILE, release builds keep
 * the debug key, as generated by Expo. The key never enters the repository.
 */
const withReleaseSigning: ConfigPlugin = (config) =>
    withAppBuildGradle(config, (mod) => {
        let gradle = mod.modResults.contents;
        if (gradle.includes(SIGNING_MARKER)) {
            return mod;
        }
        const signingConfigs = "    signingConfigs {\n        debug {";
        const releaseSigning =
            "            // see https://reactnative.dev/docs/signed-apk-android.\n            signingConfig signingConfigs.debug";
        if (
            !gradle.includes(signingConfigs) ||
            !gradle.includes(releaseSigning)
        ) {
            throw new Error(
                "withReleaseSigning: android/app/build.gradle layout changed, update app.config.ts",
            );
        }
        gradle = gradle.replace(
            signingConfigs,
            `    signingConfigs {
        release {
            // ${SIGNING_MARKER}, from the environment (app.config.ts)
            if (System.getenv("ANDROID_KEYSTORE_FILE")) {
                storeFile file(System.getenv("ANDROID_KEYSTORE_FILE"))
                storePassword System.getenv("ANDROID_KEYSTORE_PASSWORD")
                keyAlias System.getenv("ANDROID_KEY_ALIAS")
                keyPassword System.getenv("ANDROID_KEY_PASSWORD")
            }
        }
        debug {`,
        );
        gradle = gradle.replace(
            releaseSigning,
            `            // see https://reactnative.dev/docs/signed-apk-android.
            signingConfig System.getenv("ANDROID_KEYSTORE_FILE") ? signingConfigs.release : signingConfigs.debug`,
        );
        mod.modResults.contents = gradle;
        return mod;
    });

const WORKLETS_MARKER = "EpiCheck: libworklets.so for react-native-reanimated";

/**
 * react-native-reanimated 4.1 links libworklets.so from
 * react-native-worklets/android/build/intermediates/cmake/<debug|release>/obj,
 * a folder that the Android Gradle plugin fills on Linux but, on macOS,
 * without libworklets.so itself: the release build then fails with
 * "ninja: error: .../libworklets.so, needed by libreanimated.so, missing".
 * After the worklets native build, copy the library there when it is
 * missing (never over the one Gradle put), and build the worklets library
 * before the reanimated one.
 */
const withWorkletsLibraryForReanimated: ConfigPlugin = (config) =>
    withProjectBuildGradle(config, (mod) => {
        if (mod.modResults.contents.includes(WORKLETS_MARKER)) {
            return mod;
        }
        mod.modResults.contents += `
// ${WORKLETS_MARKER} (app.config.ts)
gradle.projectsEvaluated {
    def worklets = rootProject.findProject(":react-native-worklets")
    def reanimated = rootProject.findProject(":react-native-reanimated")
    if (worklets == null || reanimated == null) {
        return
    }
    ["Debug": "Debug", "Release": "RelWithDebInfo"].each { variant, cmakeType ->
        def nativeBuild = worklets.tasks.findByName("externalNativeBuild\${variant}")
        if (nativeBuild == null) {
            return
        }
        nativeBuild.doLast {
            def buildDir = worklets.layout.buildDirectory.get().asFile
            def target = new File(buildDir, "intermediates/cmake/\${variant.toLowerCase()}/obj")
            // Newest build of each ABI (the folder may also hold builds restored
            // from the Gradle cache), copied only where the library is missing:
            // on Linux the Android Gradle plugin already puts it there
            worklets.fileTree(new File(buildDir, "intermediates/cxx/\${cmakeType}"))
                .matching { include "**/obj/*/libworklets.so" }
                .files
                .groupBy { it.parentFile.name }
                .each { abi, libs ->
                    def destination = new File(target, abi)
                    if (!new File(destination, "libworklets.so").exists()) {
                        def newest = libs.max { it.lastModified() }
                        worklets.copy { from newest; into destination }
                    }
                }
        }
        reanimated.tasks.matching { it.name.startsWith("buildCMake\${cmakeType}") }.configureEach {
            dependsOn(nativeBuild)
        }
    }
}
`;
        return mod;
    });

export default ({ config }: ConfigContext): ExpoConfig => {
    const build = buildNumberOf(version);
    const withVersions: ExpoConfig = {
        ...config,
        name: config.name ?? "EpiCheck",
        slug: config.slug ?? "EpiCheck",
        version,
        ios: { ...config.ios, buildNumber: String(build) },
        android: { ...config.android, versionCode: build },
    };
    return withWorkletsLibraryForReanimated(
        withReleaseSigning(
            withXcodeVersion(withVersions, { version, build: String(build) }),
        ),
    );
};
